import { Pool } from 'pg'

let pool

const seedProjects = [
  {
    title: 'Loan Prediction System',
    description: 'A Random Forest classification model predicts the Loan_Status outcome from applicant information. Its input features include Gender, Married, Dependents, Education, Self_Employed, ApplicantIncome, CoapplicantIncome, LoanAmount, Loan_Amount_Term, Credit_History, and Property_Area.',
    technologies: ['Python', 'Machine Learning', 'Random Forest'],
  },
  {
    title: 'Typing Speed Tester',
    description: 'Typing Speed Tester is a web application for practising typing and checking typing speed. It uses Python with Flask, alongside HTML, CSS, and JavaScript. The project brings typing practice and speed checking together in one browser-based tool.',
    technologies: ['Python', 'Flask', 'HTML', 'CSS', 'JavaScript'],
  },
]

export function getDatabase() {
  if (pool) return pool

  const connectionString = process.env.DATABASE_URL
  if (!connectionString) throw new Error('DATABASE_URL is required to connect to PostgreSQL.')

  let databaseUrl
  try {
    databaseUrl = new URL(connectionString)
  } catch {
    throw new Error('DATABASE_URL must be a valid PostgreSQL connection string.')
  }
  if (!['postgres:', 'postgresql:'].includes(databaseUrl.protocol)) {
    throw new Error('DATABASE_URL must use the postgres:// or postgresql:// protocol.')
  }

  // Require certificate and hostname verification for Neon connections.
  if (databaseUrl.hostname.endsWith('.neon.tech')) {
    databaseUrl.searchParams.set('sslmode', 'verify-full')
  }

  pool = new Pool({
    connectionString: databaseUrl.toString(),
    max: Number(process.env.PG_POOL_MAX) || 5,
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 10_000,
  })
  pool.on('error', () => console.error('Unexpected idle PostgreSQL connection error.'))
  return pool
}

export async function initializeDatabase({ seed = true } = {}) {
  const database = getDatabase()
  await database.query(`
    CREATE TABLE IF NOT EXISTS projects (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title VARCHAR(120) NOT NULL UNIQUE CHECK (length(btrim(title)) BETWEEN 1 AND 120),
      description TEXT NOT NULL CHECK (length(btrim(description)) BETWEEN 1 AND 3000),
      technologies JSONB NOT NULL,
      github_url TEXT NOT NULL DEFAULT '',
      live_url TEXT NOT NULL DEFAULT '',
      featured BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `)

  if (!seed) return { database, seeded: false }

  const client = await database.connect()
  try {
    await client.query('BEGIN')
    const { rows } = await client.query('SELECT COUNT(*)::integer AS total FROM projects')
    if (rows[0].total > 0) {
      await client.query('COMMIT')
      return { database, seeded: false }
    }

    for (const project of seedProjects) {
      await client.query(`
        INSERT INTO projects (title, description, technologies)
        VALUES ($1, $2, $3::jsonb)
        ON CONFLICT (title) DO NOTHING
      `, [project.title, project.description, JSON.stringify(project.technologies)])
    }
    await client.query('COMMIT')
    return { database, seeded: true }
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {})
    throw error
  } finally {
    client.release()
  }
}

export async function closeDatabase() {
  if (!pool) return
  const activePool = pool
  pool = undefined
  await activePool.end()
}
